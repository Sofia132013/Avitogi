-- добавляем тестовые профили пользователей
-- id фиксированные, чтобы при повторном запуске не создавались дубли
-- рейтинг заранее задан, чтобы профили отличались друг от друга
-- для on conflict нужен primary key или unique по users.id

INSERT INTO users (id, name, rating)
VALUES
	(1, 'Активный покупатель', 16),
	(2, 'Активный продавец', 4),
	(3, 'Исследователь', 88),
	(4, 'Незавершенный поиск', 72),
	(5, 'Покупатель-продавец', 30 ),
	(6, 'Малоактивный пользователь', 95)
ON CONFLICT (id) DO UPDATE SET
	name = EXCLUDED.name,
	rating = EXCLUDED.rating;

-- проверяем, что пользователи добавились
SELECT id, name, rating
FROM users
ORDER BY id;
